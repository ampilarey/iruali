<h2>ބޭންކް ފައިލާއި ރެފަރެންސް</h2>
<ul>
    <li>އިރުއަލިން ފިހާރަތަކަށް ފައިސާ ދައްކަނީ ބީއެމްއެލް ބަލްކް ޓްރާންސްފަރަކުން ބެޗްތަކެއްގެ ގޮތުގައި. ބެޗެއް ޕްރޮސެސްކުރަމުންދާއިރު ތިޔަ އާމްދަނީ ޞަފްޙާގައި ޕޭއައުޓް <em>އަންނަނީ</em> ކަމަށް ބެޗް ރެފަރެންސާއެކު ފެންނާނެ (މިސާލަކަށް PB-2026-0003).</li>
    <li>ބޭންކުން ޓްރާންސްފަރު ކުރުމުން އަދަދާއި، ޕޭއައުޓް ރެފަރެންސާއި (ބެޗް/ޕޭއައުޓް ނަންބަރު، ތިޔަ ބޭންކް ސްޓޭޓްމަންޓުގައިވެސް ރިމާކެއްގެ ގޮތުގައި ފެންނާނެ) ބޭންކުގެ ރެފަރެންސާއެކު <em>ޕޭއައުޓް ފޮނުވިއްޖެ</em> އީމެއިލެއް ލިބޭނެ. ހަމަ އެ ތަފްސީލު އާމްދަނީގެ ޕޭއައުޓް ބައިގައި ހުންނާނެ.</li>
</ul>

<h2>އެޖަސްޓްމަންޓް</h2>
<ul>
    <li>އެޖަސްޓްމަންޓަކީ ތިޔަ ދެން އަންނަ ޕޭއައުޓުން ކަނޑާ (ނުވަތަ މަދުން، އިތުރުކުރާ) ފައިސާ. އާންމު އެޖަސްޓްމަންޓަކީ އެޕްރޫވްވި ރިޓާނެއް: އަނބުރާ ދިން ތަކެތީގެ ތިޔަ ބައި، އެބަހީ ކޮމިޝަން ކަނޑާފައި އެތަކެތީގެ އަގު (ބައްލަވާ <a href="{{ route('seller.help.show', 'handling-returns') }}">ރިޓާނެއް ބެލެހެއްޓުން</a>).</li>
    <li>އޯޑަރަށް ކުރިން ފައިސާ ދެއްކިޔަސް އެޖަސްޓްމަންޓް ކަނޑާނީ ދެން އަންނަ ޕޭއައުޓުން. ތައްޔާރު ފައިސާއަށްވުރެ ބޮޑުނަމަ، އާ ވިޔަފާރިން އެ ފޫބެއްދެންދެން ޕޭއައުޓެއް ނުދެވޭނެ. ހުޅުވިފައިވާ އަދި ނިމިފައިވާ އެޖަސްޓްމަންޓްތައް އާމްދަނީގައި ލިސްޓްކޮށްފައި ހުންނާނެ.</li>
</ul>
