    <li><strong>ތައްޔާރު</strong> – ތިޔަ ބައި ޑެލިވަރޑް ކަމަށް ފާހަގަކޮށްފި <em>އަދި</em> ޕޭމަންޓް ކަށަވަރުވެއްޖެ. މިހާރު އިރުއަލިއަށް ދެއްކޭނެ.</li>
    <li><strong>ދެއްކިއްޖެ</strong> – ޕޭއައުޓެއްގައި ހިމެނިއްޖެ. ކެންސަލްވި ބައިތަކަކުން އެއްވެސް އާމްދަނީއެއް ނުލިބޭނެ.</li>
</ul>

