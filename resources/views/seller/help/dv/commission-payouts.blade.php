    <li>ކޮންމެ އޯޑަރެއްގައި ރޭޓް ހަމަޖެހެނީ އޯޑަރު ކުރާ ވަގުތު؛ ފަހުން ގެންނަ ބަދަލު ހިނގާނީ އާ އޯޑަރުތަކަށް އެކަނި.</li>
