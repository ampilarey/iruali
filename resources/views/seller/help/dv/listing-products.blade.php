<h2>ފޮޓޯ</h2>
<ul>
    <li>މައިގަނޑު ފޮޓޯއެއް އަޕްލޯޑްކުރައްވާ (JPEG، PNG ނުވަތަ GIF، ގިނަވެގެން 2 އެމްބީ). ޕްރޮޑަކްޓް ލިސްޓުގައި އެންމެ ރީތިކޮށް ފެންނާނީ ހަތަރެސްކަން ފޮޓޯ؛ ފޯނަށް ކުދި ކޮޕީތައް އިރުއަލިން އަމިއްލައަށް ހަދާނެ.</li>
    <li>ދުވާލުގެ އަލީގައި، ސާދާ ބެކްގްރައުންޑެއްގައި، ސްޓޮކް ފޮޓޯއެއް ނޫން، އަސްލު އެތި ފެންނަ ގޮތަށް ނަންގަވާ. "ބުނި ގޮތާ ތަފާތު" ކަމަށް ބުނެ ކަސްޓަމަރުންނަށް ތަކެތި އަނބުރާ ދެވޭނެތީ، ފޮނުވާ އެއްޗަކާ ފޮޓޯ ދިމާވާންޖެހޭނެ.</li>
</ul>

<h2>ދެ ބަހުން ނަމާއި ތަފްސީލު</h2>
<ul>
    <li>ކޮންމެ ޕްރޮޑަކްޓަކަށް އިނގިރޭސި އަދި ދިވެހި ނަމެއް އޮންނާނެ (ޕްރޮޑަކްޓް ފޯމުގައި <em>Name (English)</em> އަދި <em>Name (Dhivehi)</em>). ދިވެހިން ބަލާ ކަސްޓަމަރުންނަށް ފެންނާނީ ދިވެހި ނަން؛ ހުސްކޮށް ބޭއްވިނަމަ އިނގިރޭސި ނަން ފެންނާނެ.</li>
    <li>އެއީ ކޯއްޗެއްކަން، ސައިޒު ނުވަތަ ބަރުދަން، ހެދިފައިވާ އެއްޗާއި ހިމެނޭ ތަކެތި ލިޔުއްވާ. ބްރޭންޑް ލިޔާނީ ނަމުގައެއް ނޫން، <em>Brand</em> ގޮޅީގައި، އޭރުން ބްރޭންޑް ފިލްޓަރު މަސައްކަތްކުރާނެ.</li>
    <li>ކޮންމެ ޕްރޮޑަކްޓަކަށް އަމިއްލަ އެސްކޭޔޫ (ތިޔަ ކޯޑެއް) ދެއްވާ. މުޅި ސައިޓުގައި ތަފާތު ކޯޑަކަށް ވާންޖެހޭނެ އަދި އޯޑަރުތަކާއި ސްޓޮކް މަދު އީމެއިލްގައި ފެންނާނެ.</li>
</ul>

<h2>އަގު</h2>
<ul>
    <li>އަގު ލިޔާނީ ދިވެހި ރުފިޔާއިން، އެ އެއްޗަކަށް ނަގާ ހުރިހާ އެއްޗެއް ހިމަނައިގެން. ޑެލިވަރީ ފީ ނަގަނީ އިރުއަލިން ވަކިން؛ އެއީ ތިޔަ ކަނޑައަޅާ އެއްޗެއް ނޫން.</li>
    <li>ޑިސްކައުންޓެއް ދައްކަން، ކުރީގެ އަގު <em>Compare-at price</em> ގައި ލިޔުއްވާ؛ އެ އަގު މިހާރުގެ އަގަށްވުރެ ބޮޑުވާންޖެހޭނެ. އޭރުން ކަސްޓަމަރުންނަށް ސަލާމަތްވާ އަދަދު ފެނި، ޕްރޮޑަކްޓް ޑީލްސްގައި ފެންނާނެ. ކައުންޓްޑައުންއެއް ދައްކަން <em>Sale ends</em> ލިޔުއްވާ.</li>
    <li>އިރުއަލިގެ ކޮމިޝަން ނަގަނީ އެތީގެ އަގުން (ބައްލަވާ <a href="{{ route('seller.help.show', 'commission-payouts') }}">ކޮމިޝަނާއި ޕޭއައުޓް</a>). އަގު ކަނޑައަޅާއިރު އެކަން ހަނދާންކުރައްވާ.</li>
</ul>

<h2>ސްޓޮކް</h2>
<ul>
    <li><em>Stock</em> އަކީ މިހާރު ފޮނުވޭނެ އަދަދު. 0 އަށް ދިއުމުން ޕްރޮޑަކްޓް ވިކި ހުސްވެފައި ކަމަށް ދައްކައި އޯޑަރެއް ނުކުރެވޭނެ؛ އަލުން ލިބުމުން އަންގައިދޭން ކަސްޓަމަރުންނަށް އެދެވޭނެ.</li>
    <li><em>Low-stock alert at</em> އަކީ އިރުއަލިން ތިޔައަށް އިންޒާރު ދޭ މިންވަރު. ކޮންމެ ހެނދުނަކު، މި މިންވަރުގައި ނުވަތަ އެއަށްވުރެ ދަށުގައި ހުރި ޕްރޮޑަކްޓްތަކާއި ވޭރިއަންޓްތަކުގެ ލިސްޓާއެކު އެއް އީމެއިލް ލިބޭނެ (ހުސްކޮށް ބޭއްވިނަމަ {{ $threshold }}). <a href="{{ route('seller.settings.notifications') }}">ސެޓިންގްސް → ނޮޓިފިކޭޝަން</a> އިން ނިއްވާލެވޭނެ.</li>
    <li>އޯޑަރެއް ކުރުމުން ސްޓޮކް މަދުވާނެ، އޯޑަރު ކެންސަލްވުމުން ނުވަތަ "އަލުން ސްޓޮކަށް ލާ" ގޮތަށް ރިޓާނެއް އެޕްރޫވްވުމުން އަލުން އިތުރުވާނެ.</li>
</ul>

